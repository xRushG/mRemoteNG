<#
    Generates the WiX fragment that installs the application's build output.

    The dependency closure of the .NET build changes with every package update,
    so this list is generated at build time instead of being maintained by hand.
    The hand-written predecessor had gone stale and shipped 99 of 213 files,
    leaving out mRemoteNG.deps.json and everything below Assemblies\, which made
    the installed application fail to start.

    Component and file identifiers are MD5 hashes of the relative path. They are
    therefore stable across runs, which keeps the auto-generated component GUIDs
    stable and major upgrades well-behaved.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string] $HarvestPath,
    [Parameter(Mandatory)] [string] $OutputFile,
    [string] $ComponentGroupId = 'MandatoryComponents'
)

$ErrorActionPreference = 'Stop'

if (!(Test-Path -LiteralPath $HarvestPath)) {
    throw "Harvest path was not found: $HarvestPath"
}

$root = (Resolve-Path -LiteralPath $HarvestPath).Path.TrimEnd('\')

# mRemoteNG.exe is installed by MainExeFragment.wxs, which owns the MainExeFile
# id that the shortcuts and WixShellExecTarget refer to.
$excludedRelativePaths = @('mRemoteNG.exe')

$files = Get-ChildItem -LiteralPath $root -Recurse -File | Where-Object {
    $rel = $_.FullName.Substring($root.Length + 1)

    if ($_.Extension -eq '.pdb') { return $false }
    if ($excludedRelativePaths -contains $rel) { return $false }

    # The package is x64-only by design. SQLitePCLRaw and the SQL client ship
    # native assets for every runtime identifier they support; only the Windows
    # ones belong in this installer.
    if ($rel -like 'runtimes\*' -and
        $rel -notlike 'runtimes\win-x64\*' -and
        $rel -notlike 'runtimes\win\*') { return $false }

    return $true
}

$md5 = [System.Security.Cryptography.MD5]::Create()

function Get-WixIdentifier([string] $prefix, [string] $relativePath) {
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($relativePath.ToLowerInvariant())
    $hex = ($md5.ComputeHash($bytes) | ForEach-Object { $_.ToString('X2') }) -join ''
    return $prefix + $hex
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">')
[void]$sb.AppendLine('  <!-- Generated by Tools\generate_installer_filelist.ps1. Do not edit. -->')
[void]$sb.AppendLine('  <Fragment>')
[void]$sb.AppendLine("    <ComponentGroup Id=`"$ComponentGroupId`">")

foreach ($file in $files | Sort-Object FullName) {
    $rel = $file.FullName.Substring($root.Length + 1)
    $subdirectory = Split-Path -Path $rel -Parent

    $componentId = Get-WixIdentifier 'cmp' $rel
    $fileId = Get-WixIdentifier 'fil' $rel
    $subdirectoryAttribute = if ($subdirectory) { " Subdirectory=`"$subdirectory`"" } else { '' }

    [void]$sb.AppendLine("      <Component Id=`"$componentId`" Directory=`"INSTALLDIR`"$subdirectoryAttribute>")
    [void]$sb.AppendLine("        <File Id=`"$fileId`" KeyPath=`"yes`" Source=`"`$(var.HarvestPath)\$rel`" />")
    [void]$sb.AppendLine('      </Component>')
}

[void]$sb.AppendLine('    </ComponentGroup>')
[void]$sb.AppendLine('  </Fragment>')
[void]$sb.AppendLine('</Wix>')

$outputDirectory = Split-Path -Path $OutputFile -Parent
if ($outputDirectory -and !(Test-Path -LiteralPath $outputDirectory)) {
    New-Item -ItemType Directory -Force -Path $outputDirectory | Out-Null
}

[System.IO.File]::WriteAllText($OutputFile, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))

Write-Host "Harvested $($files.Count) files from $root into $OutputFile"
